const HEADER = [
  'Handle',
  'Title',
  'Body (HTML)',
  'Vendor',
  'Type',
  'Tags',
  'Published',
  'Option1 Name',
  'Option1 Value',
  'Option2 Name',
  'Option2 Value',
  'Variant SKU',
  'Variant Grams',
  'Variant Inventory Tracker',
  'Variant Inventory Qty',
  'Variant Inventory Policy',
  'Variant Fulfillment Service',
  'Variant Price',
  'Variant Compare At Price',
  'Variant Requires Shipping',
  'Variant Taxable',
  'Variant Weight Unit',
  'Cost per item',
  'Status',
];

const q = (v) => {
  const s = v === null || v === undefined ? '' : String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

const rows = [HEADER];
let n = 0;
for (const [
  handle,
  title,
  type,
  vendor,
  tags,
  price,
  compareAt,
  cost,
  grams,
  sizes,
  colours,
  body,
] of P) {
  const sizeName = type === 'Shoes' ? 'Size' : sizes.length ? 'Size' : null;
  const combos = [];
  if (sizes.length) for (const c of colours) for (const s of sizes) combos.push([s, c]);
  else for (const c of colours) combos.push([null, c]);
  combos.forEach(([size, colour], i) => {
    n += 1;
    const sku = `MEN-${String(P.findIndex((p) => p[0] === handle) + 1).padStart(2, '0')}-${(colour ?? '').slice(0, 3).toUpperCase()}${size ? `-${size}` : ''}`;
    const first = i === 0;
    rows.push([
      handle,
      first ? title : '',
      first ? `<p>${body}</p>` : '',
      first ? vendor : '',
      first ? type : '',
      first ? tags : '',
      first ? 'TRUE' : '',
      // Shopify wants Option1 to be the first option; colour first, then size
      'Color',
      colour,
      size ? sizeName : '',
      size ?? '',
      sku,
      grams,
      'shopify',
      20 + ((n * 7) % 60),
      'deny',
      'manual',
      price.toFixed(2),
      compareAt ? compareAt.toFixed(2) : '',
      'TRUE',
      'TRUE',
      'g',
      cost === null ? '' : cost.toFixed(2),
      first ? 'active' : '',
    ]);
  });
}

const out = new URL('../data/mens-products.csv', import.meta.url);
mkdirSync(new URL('../data/', import.meta.url), { recursive: true });
// UTF-8 with a byte order mark so Excel opens it correctly
writeFileSync(out, '﻿' + rows.map((r) => r.map(q).join(',')).join('\r\n') + '\r\n');
process.stdout
  .write(`${P.length} products, ${rows.length - 1} variants -> packages/seed/data/mens-products.csv
`);
